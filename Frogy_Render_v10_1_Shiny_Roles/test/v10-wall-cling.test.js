'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const C=require('../public/cling.js'),Promo=require('../codes.js'),Economy=require('../economy.js');
const a=C.initial(),one={left:{wall:true,trigger:true},right:{wall:false,trigger:false}},two={left:{wall:true,trigger:true},right:{wall:true,trigger:true}};
let s=C.tick(a,1000,one);
assert(s.active&&s.hands===1);assert(Math.abs(s.seconds-4.5)<.01);
s=C.tick(s,5300,one);assert(s.active&&s.seconds<.3);
s=C.tick(s,5500,one);assert(!s.active&&s.expired,'Single paw expires before 5 seconds');
let s2=C.tick(a,1000,two);s2=C.tick(s2,6500,two);assert(s2.active,'Two hands stay attached longer');
s2=C.tick(s2,8700,two);assert(!s2.active&&s2.expired,'Even dual cling times out');
let release=C.tick(s2,8800,{left:{wall:true,trigger:false},right:{wall:true,trigger:false}});
assert(!release.active&&release.lockedUntil>=9600);
assert.equal(C.tick(release,8900,two).active,false,'Re-press cannot bypass cooldown');
assert.equal(C.tick(release,9650,two).active,true,'Rearm after cooldown');
let drop=C.tick(C.tick(a,1000,one),1300,{left:{wall:true,trigger:false}});
assert(!drop.active,'Releasing trigger instantly drops player');
assert.equal(C.tick(a,1000,one,true).active,false,'Menu disables cling');
assert(C.wallEligible(false,1000,true,1080),'Short collision jitter should not drop paw');
assert(!C.wallEligible(false,1000,true,1110),'Long contact loss releases paw');
assert(!C.wallEligible(true,1000,false,1080),'Trigger release drops even during collision grace');
assert(C.climbStroke([0,1.1,0],[0,0.95,0],.016)>.1,'Downward hand pulls frog up');
assert.equal(C.climbStroke([0,1.1,0],[0,0.32,0],.016),0,'Ignore tracking spikes');
const env={FROGY_DEV_PUBLIC_IDS:'FOWNER',FROGY_MOD_PUBLIC_IDS:'FMOD'};
const mod={publicId:'FMOD',crickets:100,dabloons:0,redeemedCodes:[]};
assert(Promo.redeem(mod,'IHVDL',env).ok);assert(mod.modTag);
assert(!Promo.redeem(mod,'IHVDL',env).ok,'MOD one use');
assert(Promo.canModerate(mod,env),'MOD only authorized while allowlisted');
assert(!Promo.canModerate(mod,{}),'Role flag alone grants no kick power');
assert(!Promo.redeem({publicId:'FOTHER',crickets:0,dabloons:0},'IHVDL',env).ok,'No public mod unlock');
const owner={publicId:'FOWNER',ownerTag:true};assert(Promo.canModerate(owner,env));
assert(!Promo.canModerate({publicId:'FOTHER',ownerTag:true},env),'Owner must remain allowlisted');
assert(Economy.normalizeProfile({...mod},'token').modTag);
const src=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
assert(src('public/game.js').includes('FrogyCling.tick'),'Cling wired into XR input');
assert(src('public/game.js').includes('clingActive){vel.y=0'),'Cling suspends gravity');
assert(src('public/game.js').includes('clingState.seconds'),'Cling timer rendered');
assert(src('public/features.js').includes('WALL STICKING'),'Tutorial includes cling instructions');
assert(src('public/features.js').includes('lobbyEnvironment(t)'));
assert(src('public/features.js').includes('const x=side*4.25,z=-1.7'),'Benches face board in redesigned lobby');
assert(src('public/voteboard.js').includes('z:-5.3'),'Original vote board stays in place');
assert(src('public/features.js').includes('promoAnimation'),'Redemption animation exists');
assert(fs.existsSync(path.join(__dirname,'../public/sounds/code_success.ogg')));
assert(src('server.js').includes("msg.type==='kickPlayer'"),'Server-side kick routing exists');
console.log('PASS v10: wall cling 4.5/7.6 sec, release/drop, cooldown, safe climbing, MOD allowlist, title, swamp lobby, vote board, code effects');
