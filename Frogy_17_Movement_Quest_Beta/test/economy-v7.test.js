'use strict';
const assert=require('node:assert/strict');
const eco=require('../economy.js');
const {SHOP}=require('../server.js');
const original={mushroom:60,crown:120,party:75,wizard:145,bow:65,glasses:70,starshades:110,mustache:45,wings:160,cape:115,backpack:85};
assert.equal(SHOP.length,Object.keys(original).length);
for(const item of SHOP)assert.equal(item.price,original[item.id]*10,`${item.id} is priced at precisely 10x v6.4`);
const before=(iso)=>Date.parse(iso);
const winter=before('2026-01-25T04:59:59Z'),summer=before('2026-07-25T03:59:59Z');
assert.equal(eco.easternDay(winter),'2026-01-24');assert.equal(eco.easternDay(summer),'2026-07-24');
assert.equal(eco.easternDay(eco.nextEasternMidnight(winter)),'2026-01-25');
assert.equal(eco.easternDay(eco.nextEasternMidnight(summer)),'2026-07-25');
const spring=before('2026-03-08T05:01:00Z'),fall=before('2026-11-01T04:01:00Z');
assert.ok(eco.nextEasternMidnight(spring)>spring);assert.ok(eco.nextEasternMidnight(fall)>fall);
const p=eco.normalizeProfile({coins:1875,inventory:['bow'],equipped:{hat:'bow'},name:'Testy'},'f'.repeat(48));
assert.equal(p.crickets,1875);assert.deepEqual(p.inventory,['bow']);
const first=eco.refreshDaily(p,'f'.repeat(48),summer);assert.equal(first,100);
const same=eco.refreshDaily(p,'f'.repeat(48),summer+300);assert.equal(same,0);
assert.equal(p.quests.entries.length,3);assert.equal(new Set(p.quests.entries.map(q=>q.id)).size,3);
const q=p.quests.entries[0],earned=eco.awardQuestEvent(p,q.event,q.target);
assert.equal(earned.earned,q.reward);assert.equal(p.dabloons,q.reward);
assert.equal(eco.awardQuestEvent(p,q.event,q.target).earned,0);
assert.equal(eco.refreshDaily(p,'f'.repeat(48),eco.nextEasternMidnight(summer)+1000),100);
assert.equal(p.quests.entries.length,3);assert.equal(p.quests.entries.filter(x=>x.claimed).length,0);
console.log('PASS v7: exact 10x cosmetic prices, EST/EDT reset, no daily reward farming, 3 rotating quests, one-time completion rewards, profile migration.');
