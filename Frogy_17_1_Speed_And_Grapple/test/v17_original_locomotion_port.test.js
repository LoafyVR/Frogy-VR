'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const M=require('../public/movement.js'),C=require('../public/collision.js'),G=require('../public/grapple.js');
const dt=1/90, rig={x:0,y:0,z:0},world={SIZE:58,cover:[]},head=[0,1.7,0];
const floor=(hand,ground=true,prev=null)=>M.contactSurface(hand,rig,ground,1.7,1,C,'arena',world,prev,head);
assert.equal(floor([0,.89,0]),null,'waist-height idle hand is not automatically planted');
assert.equal(floor([0,.89,0],true,[0,.91,0])?.type,'floor','a downward planting motion can reach the floor while standing');
assert.equal(floor([0,1.55,0]),null,'face-height hand cannot contact floor');
assert.equal(floor([0,.89,0],false),null,'airborne hand has no phantom floor');
assert.equal(floor([0,1.18,0]),null,'floating hand is not planted');
assert.equal(floor([0,.89,0],true,[-.05,.89,0]),null,'lateral empty-air stroke cannot acquire ground contact');
const held=floor([0,.89,0],true,[0,.91,0]);
const initial=M.stepHand(null,[0,.89,0],head,held,dt,1,1000);
assert(initial.contact&&!initial.push,'first contact anchors instead of launching');
const push=M.stepHand(initial.contact,[0,.855,-.035],head,held,dt,1,1011);
assert(push.push?.vz>0,'palm pushing backwards propels frog forward');
assert(push.push?.up>0,'downwards floor press makes a short hop');
assert(M.preserveJump({x:0,y:0,z:0}).y>push.push.up,'A jump remains stronger');
const release=M.stepHand(push.contact,[0,.91,.035],head,held,dt,1,1022);
assert.equal(release.push,null,'raising hand releases; return stroke cannot reverse body');
assert.equal(release.contact,null);
const air=M.stepHand(push.contact,[0,.84,.05],head,null,dt,1,1033);
assert.equal(air.push,null,'airborne hand swing cannot propel frog');
const lateral=M.stepHand(initial.contact,[.023,.89,0],head,held,dt,1,1011);
assert(lateral.push?.vx<0,'short lateral stroke registers');
const common=M.stepHand(initial.contact,[.04,.89,0],[.04,1.7,0],held,dt,1,1011);
assert.equal(common.push,null,'tracked hand/head moving together never doubles physical walking');
const lean=M.stepHand(initial.contact,[0,.89,0],[-.05,1.7,0],held,dt,1,1011);
assert.equal(lean.push,null,'head-only lean cannot create reverse force');
const both=M.applyPushes({x:0,y:0,z:0},[{vx:4,vz:0,up:0},{vx:4,vz:0,up:0}],9,true);
const one=M.applyPushes({x:0,y:0,z:0},[{vx:4,vz:0,up:0}],9,true);
assert.equal(both.vel.x,one.vel.x,'two planted hands average, never double force');
const still=M.applyPushes({x:2,y:0,z:0},[],9,true);
assert.equal(still.vel.x,2,'noncontact motion preserves current momentum');
assert(M.speedCap('playing',{monster:true})>M.speedCap('playing',{monster:false}),'Mega Frog retains speed bonus without separate movement code');
const tree={SIZE:58,cover:[{x:1,z:0,r:.6,h:4,type:'tree'}]};
const wall=M.contactSurface([1.35,1.12,0],rig,false,1.7,1,C,'arena',tree,null,head);
assert.equal(wall?.type,'wall','a real map tree remains grabbable in air');
const wallPush=M.stepHand(M.stepHand(null,[1.35,1.12,0],head,wall,dt,1,2000).contact,[1.34,1.08,0],head,wall,dt,1,2011);
assert(wallPush.push?.up>0,'real wall can produce climbing push');
// Swept test: whole trajectory intersects a thin wall even if both endpoints are clear.
const narrow={surfaceAt(p){return p[0]>.08&&p[0]<.1?{type:'wall',name:'thinWall',point:[.09,p[1],p[2]],normal:[-1,0,0]}:null;}};
const swept=M.contactSurface([.15,1.1,0],rig,false,1.7,1,narrow,'arena',null,[0,1.1,0],head);
assert.equal(swept?.name,'thinWall','swept collision detects a crossed thin wall');
assert.equal(swept?.swept,true,'crossing a thin wall is not a planted hand');
assert.equal(M.stepHand(initial.contact,[.15,1.1,0],head,swept,dt,1,3000).push,null,'swept collision must not turn open air into a push');
const far=M.contactSurface([.5,1.1,0],rig,false,1.7,1,narrow,'arena',null,[0,1.1,0],head);
assert.equal(far,null,'tracker jumps cannot invent wall hits');
assert(G.COOLDOWN_MS>=6000,'the shared 7-second tongue cooldown stays unchanged');
const game=fs.readFileSync(path.join(__dirname,'../public/game.js'),'utf8');
assert(game.includes('FrogyMotion.stepHand(')&&game.includes('FrogyMotion.applyPushes('),'VR gameplay calls the new movement implementation');
assert(!game.includes('FrogyMotion.relaxedArmStroke(')&&!game.includes('FrogyMotion.groundPress('),'old air movement shortcuts not used');
assert(game.includes('FrogyGrapple.canFireShared('),'grapple still uses shared cooldown');
assert(fs.readFileSync(path.join(__dirname,'../GORILLA_MOVEMENT_ATTRIBUTION.md'),'utf8').includes('Copyright (c) 2021 Another-Axiom'));
console.log('PASS v17 movement: planted palms, swept walls, no midair push, no reset reversal, two-hand averaging, jump, monster speed, attribution');
