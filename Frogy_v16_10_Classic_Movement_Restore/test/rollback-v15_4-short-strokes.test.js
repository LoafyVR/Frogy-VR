'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const motion=require('../public/movement.js');
const collision=require('../public/collision.js');
const game=fs.readFileSync(require('node:path').join(__dirname,'../public/game.js'),'utf8');
assert.equal(motion.settings.groundDrag,.48,'classic ground drag preserved');
assert.equal(collision.handSurface([0,.82,0],1.65,'arena',{SIZE:58,cover:[]})?.type,'floor','classic standing-height virtual paw contact restored');
assert.equal(motion.settings.monsterGravity,4.05,'classic monster behavior preserved');
assert.ok(game.includes('FrogyMotion.relaxedArmStroke(prevHands[side],raw'),'classic direct raw tracking restored');
assert.ok(!game.includes('FrogyMotion.stabilizeArmVelocity('),'post-v15.4 stabilization removed');
assert.ok(!game.includes('FrogyMotion.gateArmStroke('),'post-v15.4 reversal blocker removed');
assert.ok(!game.includes('FrogyCollision.sweepTrackedBody('),'post-v15.4 body sweep removed');
assert.ok(game.includes('const shortPush=grounded&&pushes.every'),'short-stroke treatment enabled');
const surface={type:'floor',point:[0,0,0]};
let planted=motion.strokeContact(null,[0,.82,0],surface,1/72,1.8,1000);
assert.ok(planted.contact&&!planted.push);
let n=motion.strokeContact(planted.contact,[0,.82,-.007],surface,1/72,1.8,1014);
assert.ok(n.push&&n.push.vz>0,'7mm forward stroke works');
let r=motion.relaxedArmStroke([0,1,-.01],[0,1,-.02],1/72,1.65,1.8);
assert.ok(r&&r.vz>0,'10mm relaxed stroke works');
assert.equal(motion.strokeContact(n.contact,[0,.82,-.007],null,1/72,1.8,1025).push,null,'no push on first lost-contact frame');
console.log('PASS classic movement restore: v15.4 constants, old stroke path, usable small strokes');
