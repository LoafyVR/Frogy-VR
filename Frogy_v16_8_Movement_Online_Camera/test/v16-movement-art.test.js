'use strict';
const assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path');
const M=require('../public/movement.js'), C=require('../public/collision.js'), W=require('../public/world.js');
const code=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const ordinary={monster:false,activeTools:{}}, giant={monster:true,activeTools:{}}, swift={monster:false,activeTools:{speed:true}};
const dt=1/90;
function oneStroke(n,p=ordinary){return M.strokeVelocity([{dx:n,dz:0}],dt,'playing',p)?.x||0;}
assert(oneStroke(.006)>0&&oneStroke(.006)<1,'tiny strokes remain tiny and playable');
assert(oneStroke(.04)>oneStroke(.006)*3,'large stroke travels substantially farther than small one');
assert(oneStroke(.19)<=10,'speed capped for comfort');
assert(oneStroke(.07,giant)>oneStroke(.07,ordinary),'monster has slight speed advantage');
assert(oneStroke(.07,swift)>=oneStroke(.07,ordinary),'Swift Legs keeps an advantage');
assert(M.drag(true,.2)<.35,'strong ground braking avoids sliding');
assert(M.settings.monsterGravity>M.settings.gravity*.85,'monster gravity not floaty');
assert(M.settings.monsterGravity<M.settings.gravity,'monster still lighter');
let world={SIZE:65,cover:[{x:0,z:0,r:1,h:3,type:'grass'},{x:8,z:0,r:1,h:3,type:'labwall',rot:0},{x:16,z:0,r:3,h:5,type:'shack'},{x:28,z:0,r:1,h:4,type:'tree'}]};
let grass=C.resolveBodyCircle(.1,.1,.3,'arena',world);
assert(Math.hypot(grass.x-.1,grass.z-.1)<.0001,'grass has no body collider');
let wall=C.resolveBodyCircle(8,0,.3,'arena',world);
assert(Math.abs(wall.x-8)>.4||Math.abs(wall.z)>0.4,'solid main structure has a collider');
let shack=C.resolveBodyCircle(16,0,.3,'arena',world);
assert(Math.hypot(shack.x-16,shack.z)>1.5,'large shack has substantial collider');
const tree=C.footprint({x:28,z:0,r:2,h:4,type:'tree'});
assert.equal(tree.r,1.08,'tree collision uses visible trunk instead of leaves');
let move=C.sweepBody({x:8,z:-3},{x:8,z:3},.3,'arena',world,0);
assert(move.z<-.62,'fast movement cannot tunnel through structure');
const g=code('public/game.js'),s=code('server.js');
assert(g.includes('FrogyMotion.strokeVelocity(pushes,dt,phase,me)'), 'client uses proportional stroke controller');
assert(!g.includes('Monster leaps automatically on a strong arm stroke'),'no monster automatic launch');
assert(g.includes('FrogyCollision.sweepTrackedBody'), 'client handles body walls');
assert(s.includes('FrogyCollision.resolveBodyCircle'), 'server validates structural walls');
assert(g.includes('grappleDown=edge(5)'), 'Y and B can each trigger a grapple');
assert(g.includes('tongues[side]=FrogyGrapple.activate'), 'independent hand grapples');
assert(g.includes('if(phase===\'playing\'&&me?.monster)tongues='), 'monster cannot grapple');
assert(g.includes('profile.color=m.color;if(me)me.color=m.color'), 'local paw color updates when Apply is confirmed');
assert(g.includes('V16 CUDDLEFROG'), 'new softer frog character is rendered');
assert(g.includes('cosmeticModel(p,sc)'), 'cosmetic anchors preserved');
assert(!fs.existsSync(path.join(__dirname,'..','public/luckylily.js')), 'Lucky Lily source not included');
console.log('PASS v16: proportional tiny steps, steady Mega Frog, solid walls/no grass colliders, Y+B grapple, instant skin update, cute modular avatars');
