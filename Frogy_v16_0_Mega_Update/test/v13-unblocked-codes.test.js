'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const C=require('../public/collision.js');
const M=require('../public/movement.js');
const G=require('../public/grapple.js');
const root=path.resolve(__dirname,'..');
const game=fs.readFileSync(path.join(root,'public/game.js'),'utf8');
const ui=fs.readFileSync(path.join(root,'public/features.js'),'utf8');
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
assert(game.includes('FrogyCollision.sweepBody('),'New solid structural body colliders (no decorative grass)');
assert(game.includes('FrogyCollision.sweptLanding'),'Platform tops continue to support frog feet');
assert(game.includes('FrogyCollision.handSurface('),'Hands retain separate collision against scenery');
assert.equal(C.parkour[0].h,.6);assert(C.parkour.at(-1).h>3,'Parkour course substantially taller');
assert(game.includes('FROGY_PARKOUR=FrogyCollision.parkour'),'Visual and physical course use identical platform heights');
const floor=C.handSurface([0,.47,0],1.7,'hub');
let c=M.strokeContact(null,[0,.47,0],floor,.016,1.3,1000);
c=M.strokeContact(c.contact,[0,.41,-.045],floor,.016,1.3,1016);
assert(c.push?.up>=1.5,'A downward arm press gives sufficient push-off lift');
assert(c.push?.dz>0,'Pushing backwards with the hand propels body forwards');
const tree=C.hubTrees[0],from=[tree.x+tree.r+2,1.35,tree.z];
const hit=G.raycast(from,[-1,0,0],'hub');
assert.equal(hit?.surface,'swamp tree','Grapple reaches visible/collidable tree trunks');
assert.equal(G.raycast([0,1.5,0],[0,-1,0],'hub')?.surface,'ground','Downward grapple hits ground');
assert.equal(G.raycast([0,1.5,0],[0,1,0],'hub'),null,'Empty air is never a valid grapple target');
assert(G.LIMIT>=30,'Grapple range expanded');
assert(ui.includes("send({type:'redeemCode',code:vrPromo})"),'Promo keypad sends server code');
assert(ui.includes("send({type:'join',code:vrCode"),'Room keypad sends server invite');
assert(ui.includes("vrBtn('CREATE'"),'Room terminal can create a private lobby too');
assert(server.includes("type:'roomResult'"),'Server gives explicit private room success or error receipts');
assert(server.includes('dabloons:1000'),'New profiles start with 1000 Dabloons');
console.log('PASS v13: body free of prop collision, hands and parkour intact, more forceful ground push, 38m solid-surface grapple, room and promo keypads');
