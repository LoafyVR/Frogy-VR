'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const Combat=require('../public/combat'),Collision=require('../public/collision');
const folder=path.resolve(__dirname,'..');
const survivors=[{id:'target',x:0,y:0,z:-8,alive:true,monster:true}];
const ray=[0,0,-1],origin=[0,1.8,0];
const foliage=[{type:'bush',x:0,z:-4,r:4,h:4}];
assert.equal(Combat.trace(origin,ray,foliage,survivors,'shooter').target,survivors[0], 'decorative bushes do not block a shot');
const canopy=[{type:'tree',x:1.62,z:-4,r:2.1,h:4}];
assert.equal(Combat.trace(origin,ray,canopy,survivors,'shooter').target,survivors[0], 'tree canopy does not act like a giant invisible cylinder');
const realTrunk=[{type:'tree',x:0,z:-4,r:1.8,h:4}];
assert.equal(Combat.trace(origin,ray,realTrunk,survivors,'shooter').target,null, 'tree trunk still blocks shots');
const box=[{type:'labwall',x:0,z:-4,r:2,h:4,rot:0}];
assert.equal(Combat.trace(origin,ray,box,survivors,'shooter').target,null, 'solid wall still blocks shots');
assert.equal(Collision.footprint(box[0]).kind,'box');
assert.equal(Combat.trace([0,3.4,0],ray,[],survivors,'shooter').target,survivors[0], 'upper monster hit volume covers head');
const near={id:'near',x:0,y:0,z:-2.05,alive:true,monster:true};
assert.equal(Combat.meleeTarget([0,1.3,0],ray,[],[near],'shooter',2.85),near,'sword connects from the tracked grip');
assert.equal(Combat.meleeTarget([0,1.3,0],[0,0,1],[],[near],'shooter',2.85),null,'sword cannot hit behind the hand');
assert.equal(Combat.meleeTarget([0,1.3,0],ray,[{type:'labwall',x:0,z:-1,r:1,h:3,rot:0}],[near],'shooter',2.85),null,'sword cannot cut through a wall');
const sound=fs.readFileSync(path.join(folder,'public/audio.js'),'utf8');
const game=fs.readFileSync(path.join(folder,'public/game.js'),'utf8');
const server=fs.readFileSync(path.join(folder,'server.js'),'utf8');
assert(sound.includes('sfxBus.gain.value=.64'),'sound mix reduced');
assert(game.includes("FrogyAudio.play('heartbeat',{volume:.27})"),'soft heartbeat replaces repeated round beep');
assert(game.includes('drawMonsterHealthBar(p,head)'),'health bar renders above the monster');
assert(game.includes("showRoundNotice('survivor','MEDKIT NOT NEEDED'"),'full-health message shows inside VR');
assert(game.includes("vrMenuOpen=false;vrPage='pond';"),'player can move as soon as VR starts');
assert(server.includes('monsterHealthForSurvivors('));
// Byte-for-byte preservation of the approved hand push implementation.
const approvedHash='2a7a0289f698cb0abddda6631b56993167f1d073ce38fb58bd05268a18f4957a';
const current=fs.readFileSync(path.join(folder,'public/movement.js'));
assert.equal(crypto.createHash('sha256').update(current).digest('hex'),approvedHash,'approved Frogy 17.2 movement must remain unchanged');
console.log('PASS Frogy 19: real cover vs foliage, forgiving gun and sword hitboxes, view/UI, and untouched hand physics');
