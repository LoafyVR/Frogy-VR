'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),server=fs.readFileSync(path.join(root,'server.js'),'utf8'),render=fs.readFileSync(path.join(root,'public/game.js'),'utf8');
const Motion=require('../public/movement.js');
const normal={monster:false,activeTools:{}},swift={monster:false,activeTools:{speed:true}};
assert.equal(Motion.BASE_RUN,1.8,'Normal play uses much faster arm running');
assert.equal(Motion.SWIFT_RUN,1.55,'Swift Legs has its own extra multiplier');
assert(Motion.speedCap('lobby',normal)>Motion.settings.maxHorizontalSpeed);
assert(Motion.speedCap('playing',swift)>Motion.speedCap('playing',normal)*1.5);
const surface={type:'floor',point:[0,.19,0]},dt=1/90;
function stroke(player){const power=1.15*Motion.locomotionMultiplier('playing',player);
 const planted=Motion.strokeContact(null,[0,1.02,0],surface,dt,power,1000);
 return Motion.strokeContact(planted.contact,[0,1.02,-.04],surface,dt,power,1011).push;}
assert(stroke(normal)?.vz>3,'Normal paws push strongly');
assert(stroke(swift)?.vz>stroke(normal).vz*1.25,'Swift Legs gives perceptibly faster actual strokes');
const a=server.indexOf('function newPart('),b=server.indexOf('function dropHeldPart(',a),c=server.indexOf('function stepParts(',b),d=server.indexOf('function hit(',c);
assert(a>=0&&b>a&&c>b&&d>c);
const ctx=vm.createContext({crypto,WorldData:{SIZE:65},Date,Math});
vm.runInContext(server.slice(a,b)+server.slice(c,d)+'\n;this.newPart=newPart;this.stepParts=stepParts;',ctx);
const p={id:'one',x:2,y:0,z:3,yaw:0,monster:false,color:'mint'},r={parts:[],players:new Map([['one',p]])};
const left=ctx.newPart(r,p,'arm','left',[0,0,-1]),right=ctx.newPart(r,p,'arm','right',[0,0,-1]);
assert(left.id!==right.id);assert(left.x<p.x&&right.x>p.x,'each arm spawns at correct shoulder');
assert.equal(left.y,1.08,'initial arm height is shoulder height');
assert(left.vy<0&&right.vy<0,'ripped arms start falling, not launching straight upward');
assert(left.spin!==undefined&&right.spin!==undefined,'parts have tumble/spin');
const before=left.y;ctx.stepParts(r,1/20);assert(left.y<before,'gravity moves severed limb down');
for(let i=0;i<40;i++)ctx.stepParts(r,1/20);
assert(left.y>=.23&&right.y>=.23,'floor bounce stops arms falling through ground');
assert(render.includes('paw(tip,.38,c,twist)'),'detached arm has a three-finger paw still connected');
assert(render.includes('No visible paw for a detached arm'),'missing arm is not drawn on local frog');
assert(server.includes('if(!(target.lostArms&1))newPart'),'death never duplicates previously ripped left arm');
assert(server.includes('if(!(target.lostArms&2))newPart'),'death never duplicates previously ripped right arm');
console.log('PASS v15.3 rip/movement: faster natural stroke, stronger Swift Legs, shoulder-spawned arms tumble/fall/bounce, no duplicates and paw is visible');
